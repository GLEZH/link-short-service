// Package main generates Reset methods for marked structures
package main

import (
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"golang.org/x/tools/go/packages"
)

//go:generate go run .

const (
	generatedFileName = "reset.gen.go"
	resetMarker       = "generate:reset"
)

var resetter = newResetterInterface()

type resetStruct struct {
	name  string
	named *types.Named
	value *types.Struct
}

type resetType struct {
	packagePath string
	name        string
}

type generatedMethod struct {
	code      string
	needsZero bool
}

func main() {
	if err := run(); err != nil {
		log.Fatal(err)
	}
}

func run() error {
	root, err := moduleRoot()
	if err != nil {
		return err
	}
	return generate(root)
}

func moduleRoot() (string, error) {
	dir, err := os.Getwd()
	if err != nil {
		return "", fmt.Errorf("get working directory: %w", err)
	}

	for {
		_, err = os.Stat(filepath.Join(dir, "go.mod"))
		if err == nil {
			return dir, nil
		}
		if !errors.Is(err, os.ErrNotExist) {
			return "", fmt.Errorf("find go.mod: %w", err)
		}

		parent := filepath.Dir(dir)
		if parent == dir {
			return "", errors.New("go.mod not found")
		}
		dir = parent
	}
}

func generate(root string) error {
	config := &packages.Config{
		Dir: root,
		Mode: packages.NeedName |
			packages.NeedFiles |
			packages.NeedCompiledGoFiles |
			packages.NeedSyntax |
			packages.NeedTypes |
			packages.NeedTypesInfo,
	}

	loaded, err := packages.Load(config, "./...")
	if err != nil {
		return fmt.Errorf("load packages: %w", err)
	}
	if count := packages.PrintErrors(loaded); count > 0 {
		return fmt.Errorf("load packages: %d errors", count)
	}

	sort.Slice(loaded, func(i, j int) bool {
		return loaded[i].PkgPath < loaded[j].PkgPath
	})

	marked := make(map[resetType]struct{})
	structures := make(map[string][]resetStruct, len(loaded))
	for _, pkg := range loaded {
		found := findResetStructs(pkg)
		structures[pkg.PkgPath] = found
		for _, structure := range found {
			marked[resetType{packagePath: pkg.PkgPath, name: structure.name}] = struct{}{}
		}
	}

	for _, pkg := range loaded {
		if err = generatePackage(pkg, structures[pkg.PkgPath], marked); err != nil {
			return err
		}
	}

	return nil
}

func findResetStructs(pkg *packages.Package) []resetStruct {
	var structures []resetStruct

	for _, file := range pkg.Syntax {
		if ast.IsGenerated(file) {
			continue
		}

		for _, declaration := range file.Decls {
			general, ok := declaration.(*ast.GenDecl)
			if !ok || general.Tok != token.TYPE {
				continue
			}

			for _, specification := range general.Specs {
				typeSpec, ok := specification.(*ast.TypeSpec)
				if !ok || typeSpec.Assign.IsValid() {
					continue
				}

				doc := typeSpec.Doc
				if doc == nil && len(general.Specs) == 1 {
					doc = general.Doc
				}
				if !hasResetMarker(doc) {
					continue
				}

				object, ok := pkg.TypesInfo.Defs[typeSpec.Name].(*types.TypeName)
				if !ok {
					continue
				}
				named, ok := object.Type().(*types.Named)
				if !ok {
					continue
				}
				value, ok := named.Underlying().(*types.Struct)
				if !ok {
					continue
				}

				structures = append(structures, resetStruct{
					name:  typeSpec.Name.Name,
					named: named,
					value: value,
				})
			}
		}
	}

	sort.Slice(structures, func(i, j int) bool {
		return structures[i].name < structures[j].name
	})
	return structures
}

func hasResetMarker(group *ast.CommentGroup) bool {
	if group == nil {
		return false
	}

	for _, comment := range group.List {
		text := strings.TrimSpace(strings.TrimPrefix(comment.Text, "//"))
		if text == resetMarker {
			return true
		}
	}
	return false
}

func generatePackage(pkg *packages.Package, structures []resetStruct, marked map[resetType]struct{}) error {
	dir, err := packageDir(pkg)
	if err != nil {
		return err
	}
	outputPath := filepath.Join(dir, generatedFileName)

	if len(structures) == 0 {
		if err = os.Remove(outputPath); err != nil && !errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("remove %s: %w", outputPath, err)
		}
		return nil
	}

	zeroHelper := zeroHelperName(pkg)
	methods := make([]generatedMethod, 0, len(structures))
	needsZero := false
	for _, structure := range structures {
		method := generateMethod(structure, marked, zeroHelper)
		methods = append(methods, method)
		needsZero = needsZero || method.needsZero
	}

	var source strings.Builder
	source.WriteString("// Code generated by reset; DO NOT EDIT.\n\n")
	source.WriteString("package ")
	source.WriteString(pkg.Name)
	source.WriteString("\n\n")
	if needsZero {
		source.WriteString("func ")
		source.WriteString(zeroHelper)
		source.WriteString("[T any](value *T) {\n")
		source.WriteString("\tvar zero T\n")
		source.WriteString("\t*value = zero\n")
		source.WriteString("}\n\n")
	}
	for i, method := range methods {
		source.WriteString(method.code)
		if i < len(methods)-1 {
			source.WriteByte('\n')
		}
	}

	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return fmt.Errorf("format %s: %w", outputPath, err)
	}
	if err = os.WriteFile(outputPath, formatted, 0o644); err != nil {
		return fmt.Errorf("write %s: %w", outputPath, err)
	}
	return nil
}

func packageDir(pkg *packages.Package) (string, error) {
	for _, filename := range pkg.CompiledGoFiles {
		if filepath.Base(filename) != generatedFileName {
			return filepath.Dir(filename), nil
		}
	}
	if len(pkg.CompiledGoFiles) > 0 {
		return filepath.Dir(pkg.CompiledGoFiles[0]), nil
	}
	return "", fmt.Errorf("package %s has no source files", pkg.PkgPath)
}

func zeroHelperName(pkg *packages.Package) string {
	const baseName = "resetGenZero"

	for suffix := 1; ; suffix++ {
		name := baseName
		if suffix > 1 {
			name += fmt.Sprint(suffix)
		}

		object := pkg.Types.Scope().Lookup(name)
		if object == nil || filepath.Base(pkg.Fset.Position(object.Pos()).Filename) == generatedFileName {
			return name
		}
	}
}

func generateMethod(
	structure resetStruct,
	marked map[resetType]struct{},
	zeroHelper string,
) generatedMethod {
	var method strings.Builder
	method.WriteString("func (v *")
	method.WriteString(receiverType(structure.named))
	method.WriteString(") Reset() {\n")
	method.WriteString("\tif v == nil {\n")
	method.WriteString("\t\treturn\n")
	method.WriteString("\t}\n\n")

	needsZero := false
	for i := 0; i < structure.value.NumFields(); i++ {
		field := structure.value.Field(i)
		if field.Name() == "_" {
			continue
		}
		needsZero = writeReset(&method, "v."+field.Name(), field.Type(), 1, marked, zeroHelper) || needsZero
	}

	method.WriteString("}\n")
	return generatedMethod{code: method.String(), needsZero: needsZero}
}

func receiverType(named *types.Named) string {
	name := named.Obj().Name()
	parameters := named.TypeParams()
	if parameters == nil || parameters.Len() == 0 {
		return name
	}

	names := make([]string, 0, parameters.Len())
	for i := 0; i < parameters.Len(); i++ {
		names = append(names, parameters.At(i).Obj().Name())
	}
	return name + "[" + strings.Join(names, ", ") + "]"
}

func writeReset(
	output *strings.Builder,
	expression string,
	typeOf types.Type,
	indent int,
	marked map[resetType]struct{},
	zeroHelper string,
) bool {
	switch underlying := typeOf.Underlying().(type) {
	case *types.Pointer:
		writeLine(output, indent, "if %s != nil {", expression)
		needsZero := writeReset(output, "(*"+expression+")", underlying.Elem(), indent+1, marked, zeroHelper)
		writeLine(output, indent, "}")
		return needsZero
	case *types.Slice:
		writeLine(output, indent, "%s = %s[:0]", expression, expression)
	case *types.Map:
		writeLine(output, indent, "clear(%s)", expression)
	case *types.Struct:
		if hasResetMethod(typeOf, marked) {
			writeLine(output, indent, "%s.Reset()", expression)
			return false
		}
		writeLine(output, indent, "%s(&%s)", zeroHelper, expression)
		return true
	case *types.Basic:
		if literal, ok := zeroLiteral(underlying); ok {
			writeLine(output, indent, "%s = %s", expression, literal)
			return false
		}
		writeLine(output, indent, "%s(&%s)", zeroHelper, expression)
		return true
	default:
		writeLine(output, indent, "%s(&%s)", zeroHelper, expression)
		return true
	}
	return false
}

func writeLine(output *strings.Builder, indent int, format string, values ...any) {
	output.WriteString(strings.Repeat("\t", indent))
	_, _ = fmt.Fprintf(output, format, values...)
	output.WriteByte('\n')
}

func zeroLiteral(basic *types.Basic) (string, bool) {
	switch basic.Kind() {
	case types.Bool:
		return "false", true
	case types.String:
		return `""`, true
	case types.Int, types.Int8, types.Int16, types.Int32, types.Int64,
		types.Uint, types.Uint8, types.Uint16, types.Uint32, types.Uint64,
		types.Uintptr, types.Float32, types.Float64, types.Complex64, types.Complex128:
		return "0", true
	case types.UnsafePointer:
		return "nil", true
	default:
		return "", false
	}
}

func hasResetMethod(typeOf types.Type, marked map[resetType]struct{}) bool {
	if isMarked(typeOf, marked) || types.Implements(typeOf, resetter) {
		return true
	}
	_, isStruct := typeOf.Underlying().(*types.Struct)
	return isStruct && types.Implements(types.NewPointer(typeOf), resetter)
}

func isMarked(typeOf types.Type, marked map[resetType]struct{}) bool {
	named, ok := typeOf.(*types.Named)
	if !ok || named.Obj().Pkg() == nil {
		return false
	}
	_, ok = marked[resetType{packagePath: named.Obj().Pkg().Path(), name: named.Obj().Name()}]
	return ok
}

func newResetterInterface() *types.Interface {
	signature := types.NewSignatureType(nil, nil, nil, nil, nil, false)
	method := types.NewFunc(token.NoPos, nil, "Reset", signature)
	return types.NewInterfaceType([]*types.Func{method}, nil).Complete()
}
